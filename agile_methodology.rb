=================================== Agile methodology ==================================================

Question 1: What is Agile methodology?

Answer: -> Agile is an iterative and incremental approach to software development where we build the product in small chunks, get feedback frequently, and adapt to change quickly. The focus is on delivering working software continuously rather than following a rigid long-term plan.

------------------------------------------------------------------------------------------------------
Question 2: Why Agile is preferred over Waterfall?

Answer: -> Agile is preferred because requirements often change during development. Unlike Waterfall, Agile allows continuous feedback, faster delivery, and early detection of issues. This reduces risk and improves customer satisfaction.
 
------------------------------------------------------------------------------------------------------
Question 3: What are the core values of Agile?

Answer: -> Agile values individuals and interactions over processes, working software over documentation, customer collaboration over contract negotiation, and responding to change over following a plan.

------------------------------------------------------------------------------------------------------
Question 4: What are the Agile principles?

Answer: -> Agile principles focus on early and continuous delivery, welcoming changing requirements, close collaboration between business and development teams, frequent feedback, and sustainable development.
 
------------------------------------------------------------------------------------------------------
Question 5: What Agile frameworks have you worked with?

Answer: -> I have mainly worked with Scrum-based Agile. I understand Kanban at a conceptual level, but my day-to-day experience has mostly been Scrum.

------------------------------------------------------------------------------------------------------
Question 6: What is Scrum?

Answer: ->  Scrum is an Agile framework used to manage work in iterations called sprints. It defines specific roles, ceremonies, and artifacts to help teams deliver value incrementally.

------------------------------------------------------------------------------------------------------
Question 7: What are the roles in Scrum?

Answer: -> Scrum has three main roles: Product Owner, Scrum Master, and Development Team. The Product Owner manages requirements, the Scrum Master facilitates the process, and the Development Team delivers the product.
 
------------------------------------------------------------------------------------------------------
Question 8: What does a Product Owner do?

Answer: -> The Product Owner owns the product backlog, prioritizes user stories, and ensures the team is building the right features based on business value.
 
------------------------------------------------------------------------------------------------------
Question 9: What is the role of a Scrum Master?

Answer: -> The Scrum Master ensures that Scrum practices are followed, removes blockers, and helps the team improve continuously. They act as a facilitator, not a manager.
 
------------------------------------------------------------------------------------------------------
Question 10: What is a Sprint?

Answer: -> A sprint is a fixed time-box, usually 1-2 weeks, during which the team delivers a potentially shippable increment of the product.

------------------------------------------------------------------------------------------------------
Question 12: What happens in Sprint Planning?

Answer: -> In sprint planning, the team selects user stories from the backlog, breaks them into tasks, and commits to what can be delivered during the sprint.

------------------------------------------------------------------------------------------------------
Question 13: What is a Daily Standup?

Answer: -> The daily standup is a short meeting where team members discuss what they did yesterday, what they will do today, and any blockers they are facing.
 
------------------------------------------------------------------------------------------------------
Question 14: What is Sprint Review?

Answer: -> In sprint review, the team demonstrates completed work to stakeholders and collects feedback. It ensures transparency and alignment.

------------------------------------------------------------------------------------------------------
Question 15: What is Sprint Retrospective?

Answer: -> The retrospective is used to reflect on the sprint process—what went well, what didn’t, and what can be improved in the next sprint.
 
------------------------------------------------------------------------------------------------------
Question 16: What are Scrum artifacts?

Answer: -> The main Scrum artifacts are Product Backlog, Sprint Backlog, and Increment. They help maintain transparency and track progress.
 
------------------------------------------------------------------------------------------------------
Question 17: What is a user story?

Answer: -> A user story is a simple description of a feature written from the users perspective, usually in the format: As a user, I want to do something, so that I get some benefit.
 
------------------------------------------------------------------------------------------------------
Question 18: What is acceptance criteria?

Answer: -> Acceptance criteria define the conditions under which a user story is considered complete. They remove ambiguity and help developers and testers align on expectations.
 
------------------------------------------------------------------------------------------------------
Question 19: What is backlog grooming / refinement?

Answer: -> Backlog refinement is the process of reviewing, prioritizing, and breaking down user stories so they are ready for future sprints.
 
------------------------------------------------------------------------------------------------------
Question 20: How do you estimate tasks in Agile?

Answer: ->  We usually estimate using story points based on complexity, effort, and risk. Techniques like planning poker are commonly used.
 
------------------------------------------------------------------------------------------------------
Question 21: What are story points?

Answer: -> Story points are a relative measure of effort, not time. They help compare the complexity of tasks rather than estimating exact hours.
 
------------------------------------------------------------------------------------------------------
Question 22: How does Agile help developers?

Answer: -> Agile gives developers clarity through smaller tasks, continuous feedback, and realistic goals. It also reduces last-minute pressure and improves collaboration.

------------------------------------------------------------------------------------------------------
Question 23: How do you handle changing requirements in Agile?

Answer: -> Agile welcomes change. New or changed requirements are added to the backlog, prioritized, and picked up in future sprints instead of disrupting ongoing work.
 
------------------------------------------------------------------------------------------------------
Question 24: How do you ensure quality in Agile?

Answer: ->  Quality is ensured through continuous testing, code reviews, CI pipelines, and by delivering small increments frequently instead of large risky releases.”

------------------------------------------------------------------------------------------------------
Question 25: What is "Definition of Done"?

Answer: -> Definition of Done is a shared agreement that defines when a task or user story is considered complete—for example, code reviewed, tested, and deployed.

------------------------------------------------------------------------------------------------------
Question 26: Agile documentation - is it ignored?

Answer: -> No, Agile values working software over excessive documentation, but documentation still exists. It is just kept lightweight and relevant.
 
------------------------------------------------------------------------------------------------------
Question 27: What is Kanban?

Answer: -> Kanban is an Agile method focused on visualizing work, limiting work in progress, and improving flow rather than working in fixed sprints.

------------------------------------------------------------------------------------------------------
Question 28: Scrum vs Kanban?

Answer: -> Scrum uses fixed sprints and defined roles, while Kanban is continuous with no fixed iterations and focuses on workflow optimization.

------------------------------------------------------------------------------------------------------
Question 29: What is velocity?

Answer: -> Velocity measures how many story points a team completes in a sprint. It helps with future planning but should not be used as a performance metric.

------------------------------------------------------------------------------------------------------
Question 30: What is a burndown chart?

Answer: -> A burndown chart shows remaining work over time in a sprint, helping teams track progress and spot issues early.”

------------------------------------------------------------------------------------------------------
Question 31: How do you handle missed sprint commitments?

Answer: -> If a sprint goal is missed, we discuss it in the retrospective, understand the root cause, and improve planning or execution in the next sprint.
 
------------------------------------------------------------------------------------------------------
Question 32: What if a developer finishes tasks early?

Answer: -> They can help other team members, improve code quality, or pick up additional backlog items after team discussion.

------------------------------------------------------------------------------------------------------
Question 33: What if stakeholders push unrealistic deadlines?

Answer: -> We use data like velocity and backlog priorities to explain trade-offs clearly and help stakeholders make informed decisions.

 